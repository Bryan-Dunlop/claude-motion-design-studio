// A1: "Single-draw layers keep the direct path, so v1 files (no effects) render exactly as before." The draw calls for
// a v1-style project (every layer type, keyframes, a missing and a loaded image, a cursor click, two scenes) must stay
// identical to what the v1 renderer recorded. (A2/A3 must keep these too when no new feature is in use.)
import { describe, expect, it } from 'vitest';
import { makeProject } from '../../src/shared/factories';
import { renderFrame } from '../../src/shared/renderFrame';
import { recordingCtx } from './helpers/recordingCtx';

function v1Project() {
  const base = { visible: true, locked: false, start: 0, duration: 4, anchorX: 0.5, anchorY: 0.5, scale: 1, rotation: 0, opacity: 1, keyframes: {} };
  return makeProject({
    schemaVersion: 2,
    settings: { durationSec: 4, aspect: '16:9', width: 1920, height: 1080, fps: 30, background: '#102030' },
    assets: [],
    scenes: [
      { id: 's1', name: 'A', start: 0, duration: 4, layers: [
        { ...base, id: 't1', name: 'T1', type: 'text', x: 960, y: 300, content: 'Hello\nWorld two', fontFamily: 'Inter', fontSize: 80, fontWeight: 700, lineHeight: 1.2, letterSpacing: 2, align: 'center', color: '#ffffff',
          keyframes: { x: [{ id: 'a', time: 0, value: 100, easing: { type: 'easeOut' } }, { id: 'b', time: 2, value: 900, easing: { type: 'linear' } }] } },
        { ...base, id: 't2', name: 'T2', type: 'text', x: 400, y: 800, rotation: 12, content: 'Single', fontFamily: 'Inter', fontSize: 50, fontWeight: 400, lineHeight: 1.1, letterSpacing: 0, align: 'right', color: '#ff0', opacity: 0.5 },
        { ...base, id: 'r1', name: 'R1', type: 'shape', x: 600, y: 500, shape: 'rect', width: 300, height: 200, cornerRadius: 20, fill: '#ff7a3d', stroke: '#ffffff', strokeWidth: 6,
          keyframes: { rotation: [{ id: 'c', time: 0, value: 0, easing: { type: 'easeInOut' } }, { id: 'd', time: 3, value: 90, easing: { type: 'linear' } }] } },
        { ...base, id: 'e1', name: 'E1', type: 'shape', x: 1200, y: 500, scale: 1.5, shape: 'ellipse', width: 200, height: 120, cornerRadius: 0, fill: '#22c55e', stroke: '#000', strokeWidth: 0 },
        { ...base, id: 'i1', name: 'I1', type: 'image', x: 1500, y: 300, assetId: 'missing', width: 320, height: 240 },
        { ...base, id: 'i2', name: 'I2', type: 'image', x: 1500, y: 800, assetId: 'loaded', width: 200, height: 100, anchorX: 0, anchorY: 0 },
        { ...base, id: 'c1', name: 'C', type: 'cursor', x: 0, y: 0, anchorX: 0, anchorY: 0,
          points: [{ id: 'p1', x: 200, y: 200, time: 0 }, { id: 'p2', x: 1000, y: 500, time: 1.5 }, { id: 'p3', x: 1500, y: 300, time: 2.8 }],
          clicks: [{ id: 'k1', time: 1.5 }], smoothing: 0.6, size: 40, color: '#ffffff', rippleColor: '#ffffff66' },
      ] },
      { id: 's2', name: 'B', start: 2, duration: 2, layers: [
        { ...base, id: 'r2', name: 'R2', type: 'shape', x: 300, y: 300, shape: 'rect', width: 100, height: 100, cornerRadius: 0, fill: '#0000ff', stroke: '#fff', strokeWidth: 0, duration: 2 },
      ] },
    ],
  });
}

describe('v1 compatibility', () => {
  it('a project without effects, backgrounds or transitions draws exactly the v1 calls', () => {
    const images = new Map<string, CanvasImageSource>([['loaded', { name: 'img', width: 200, height: 100 } as unknown as CanvasImageSource]]);
    const p = v1Project();
    for (const t of Object.keys(V1_LOG)) {
      const rec = recordingCtx(1920, 1080);
      renderFrame(p, Number(t), rec.ctx, 0.5, { images, canvasPool: rec.pool });
      expect(rec.log, `t=${t}`).toEqual(V1_LOG[t]);
      expect(rec.children).toHaveLength(0);
      expect(rec.releases()).toBe(1);
    }
  });
});

